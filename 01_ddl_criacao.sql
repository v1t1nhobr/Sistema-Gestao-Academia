CREATE TABLE usuarios (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    telefone VARCHAR(20),
    data_cadastro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    tipo_perfil VARCHAR(10) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,

    CONSTRAINT chk_usuario_perfil
        CHECK (tipo_perfil IN ('ADMIN', 'ALUNO'))
);

CREATE TABLE equipamentos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    categoria VARCHAR(80) NOT NULL,
    numero_serie VARCHAR(100) UNIQUE,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    observacoes TEXT
);

CREATE TABLE mensalidades (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER NOT NULL,
    valor NUMERIC(10,2) NOT NULL,
    data_vencimento DATE NOT NULL,
    data_pagamento DATE,
    status VARCHAR(15) NOT NULL DEFAULT 'PENDENTE',

    CONSTRAINT fk_mensalidade_usuario
        FOREIGN KEY (usuario_id)
        REFERENCES usuarios(id)
        ON DELETE RESTRICT,

    CONSTRAINT chk_mensalidade_valor
        CHECK (valor > 0),

    CONSTRAINT chk_mensalidade_status
        CHECK (status IN ('PENDENTE', 'PAGA', 'ATRASADA')),

    CONSTRAINT chk_mensalidade_pagamento
        CHECK (
            (status = 'PAGA' AND data_pagamento IS NOT NULL)
            OR
            (status <> 'PAGA' AND data_pagamento IS NULL)
        )
);

CREATE TABLE treinos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER NOT NULL,
    descricao TEXT NOT NULL,
    duracao_minutos INTEGER NOT NULL,
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_treino_usuario
        FOREIGN KEY (usuario_id)
        REFERENCES usuarios(id)
        ON DELETE RESTRICT,

    CONSTRAINT chk_treino_duracao
        CHECK (duracao_minutos > 0)
);

CREATE TABLE manutencoes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipamento_id INTEGER NOT NULL,
    tipo VARCHAR(30) NOT NULL,
    descricao TEXT NOT NULL,
    custo NUMERIC(10,2) NOT NULL DEFAULT 0,
    data_manutencao DATE NOT NULL,
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_manutencao_equipamento
        FOREIGN KEY (equipamento_id)
        REFERENCES equipamentos(id)
        ON DELETE RESTRICT,

    CONSTRAINT chk_manutencao_custo
        CHECK (custo >= 0)
);

CREATE TABLE itens_treino (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    treino_id INTEGER NOT NULL,
    equipamento_id INTEGER,
    exercicio VARCHAR(120) NOT NULL,
    series INTEGER NOT NULL,
    repeticoes INTEGER NOT NULL,
    observacoes TEXT,

    CONSTRAINT fk_item_treino
        FOREIGN KEY (treino_id)
        REFERENCES treinos(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_item_equipamento
        FOREIGN KEY (equipamento_id)
        REFERENCES equipamentos(id)
        ON DELETE SET NULL,

    CONSTRAINT chk_item_series
        CHECK (series > 0),

    CONSTRAINT chk_item_repeticoes
        CHECK (repeticoes > 0)
);
